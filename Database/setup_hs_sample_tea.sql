        SELECT 'HS_SMRI', 'Sample Gain Loss Register', '1', 'HS_SMR!1', '05020200T' FROM dual) n
WHERE  NOT EXISTS (SELECT 1 FROM VBMENU_HOSALES x WHERE x.MODULE = 'HS' AND x.ORDERCODE = n.OC)
AND    NOT EXISTS (SELECT 1 FROM VBMENU_HOSALES x WHERE x.MODULE = 'HS' AND x.ID = n.ID AND x.INDEX_ORA = n.IX);

-- 4. Move Tea Sample Receive Entry under Sample Tea > Inputs (row + screen mapping)
UPDATE VBMENU_HOSALES SET PID = 'HS_SMP!0', ORDERCODE = '05010200T'
WHERE  MODULE = 'HS' AND ID = 'HS_INP' AND INDEX_ORA = '8' AND ORDERCODE <> '05010200T'
AND    NOT EXISTS (SELECT 1 FROM VBMENU_HOSALES x WHERE x.MODULE = 'HS' AND x.ORDERCODE = '05010200T');

UPDATE VBMENU_DONE SET MENUCODE = '05010200T'
WHERE  MODULECODE = 'HS' AND CONTROLLER = 'TeaSampleReceive' AND MENUCODE <> '05010200T';

