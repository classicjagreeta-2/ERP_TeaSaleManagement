       h.PRNM, h.PGSZ, h.ORNT, h.FNTSZ, h.FNTNM, h.DTLOCK, h.MACHINE_NO, h.TMPORDER, h.FTEXT, 'HS', 'Y', 'Y', 'HS'
FROM   (SELECT * FROM VBMENU_HOSALES WHERE MODULE = 'HS' AND ID = 'HS_INP' AND INDEX_ORA = '8' AND ROWNUM = 1) h,
       (SELECT 'HS_SMPI' ID, 'Sample Drawing Entry' NAME, '0' IX, 'HS_SMP!0' PID, '05010100T' OC FROM dual UNION ALL
